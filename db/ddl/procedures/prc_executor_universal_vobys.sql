
  CREATE OR REPLACE EDITIONABLE PROCEDURE "JOSEGOMES"."PRC_EXECUTOR_UNIVERSAL_VOBYS" AS
    v_sql_template CLOB;
    v_sql_final    CLOB;
BEGIN
    -- Limpa a tabela de destino
    EXECUTE IMMEDIATE 'TRUNCATE TABLE STG_RELATORIO_LICENCAS';

    -- Template com a sua query exata
    v_sql_template := '
        INSERT INTO STG_RELATORIO_LICENCAS
        SELECT
            ''{sigla_orgao}'',
            E.SIGLA, E2.SIGLA, PV.COD_INSTITUCIONAL, HN.NOME, PDC.CPF_PESSOA, 
            PD.NOME_DIVISAO, PS.NOME_SITUACAO, TF.NOME_TIPO_FUNCIONARIO, RM.NOME_REMUNERACAO,
            LA.ID_LICENCA, LA.NOME_LICENCA, FL.DATA_CADASTRO, FL.EFEITO_FINANCEIRO,
            FL.DATA_SOLICITACAO, FL.DATA_INICIO_AQUISICAO, FL.DATA_FIM_AQUISICAO,
            FL.DATA_PREVISTA_RETORNO, FL.DIAS_LICENCA, FL.OBSERVACAO
        FROM SW_{tabela}.PESSOA_VINCULO PV
        JOIN SW_PUBLICO.PESSOA_HISTORICO_NOMES HN ON HN.ID_PESSOA = PV.ID_PESSOA AND HN.DATA_FIM IS NULL
        JOIN SW_PUBLICO.PESSOA_DOC_CPF PDC ON PDC.ID_PESSOA = PV.ID_PESSOA AND PDC.DATA_BAIXA IS NULL
        JOIN SW_{tabela}.FUNCIONARIO F ON F.ID_PESSOA_VINCULO = PV.ID_PESSOA_VINCULO
        JOIN SW_{tabela}.FUNCIONARIO_INGRESSO FI ON FI.ID_FUNCIONARIO = F.ID_FUNCIONARIO
        JOIN SW_{tabela}.FUNCIONARIO_PERFIL FP ON FP.ID_FUNCIONARIO = F.ID_FUNCIONARIO
        JOIN SW_{tabela}.RHB_PERFIL P ON P.ID_PERFIL = FP.ID_PERFIL
        JOIN SW_PUBLICO.RHB_PERFIL_DIVISAO PD ON PD.ID_DIVISAO = P.ID_DIVISAO
        JOIN SW_PUBLICO.RHB_PERFIL_SITUACAO PS ON PS.ID_SITUACAO = P.ID_SITUACAO
        JOIN SW_PUBLICO.RHB_PERFIL_TIPO_FUNCIONARIO TF ON TF.ID_TIPO_FUNCIONARIO = FP.ID_TIPO_FUNCIONARIO
        JOIN SW_PUBLICO.RHB_INGRESSO_REMUNERACAO RM ON RM.ID_REMUNERACAO = FP.ID_REMUNERACAO
        JOIN SW_{tabela}.FUNC_FREQ_LICENCA FL ON FL.ID_FUNCIONARIO = F.ID_FUNCIONARIO
        JOIN SW_PUBLICO.RHB_LICENCA_AFASTAMENTO LA ON LA.ID_LICENCA = FL.ID_LICENCA
        LEFT JOIN SW_PUBLICO.FUNC_CESSAO_REQUISICAO_I CRI ON CRI.ID_PESSOA = PV.ID_PESSOA 
             AND (CRI.ID_FUNCIONARIO_CESSAO = F.ID_FUNCIONARIO OR CRI.ID_FUNCIONARIO_REQUISICAO = F.ID_FUNCIONARIO)
             AND CRI.DATA_FIM IS NULL
        LEFT JOIN SW_PUBLICO.EMPRESA E ON E.ID_EMPRESA = CRI.ID_EMPRESA_CESSAO
        LEFT JOIN SW_PUBLICO.EMPRESA E2 ON E2.ID_EMPRESA = CRI.ID_EMPRESA_REQUISITANTE
        WHERE EXTRACT(YEAR FROM FL.DATA_CADASTRO) >= 2023';

    -- Loop pelos schemas conforme seu print da FOLHA_FUNC
    FOR r IN (SELECT owner FROM all_tables 
               WHERE table_name = 'FOLHA_FUNC' 
                 AND owner LIKE 'SW_%' 
                 AND owner NOT IN ('SW_PUBLICO', 'SW_MODELO')) 
    LOOP
        -- Prepara o SQL substituindo os placeholders
        v_sql_final := REPLACE(v_sql_template, '{tabela}', REPLACE(r.owner, 'SW_', ''));
        v_sql_final := REPLACE(v_sql_final, '{sigla_orgao}', REPLACE(r.owner, 'SW_', ''));

        -- Executa a carga do órgão atual
        EXECUTE IMMEDIATE v_sql_final;
    END LOOP;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'Erro ao processar carga multitenant: ' || SQLERRM);
END;
;
